CREATE TABLE RESUMEN_GESTION_ROARMA(
    ID_RESUMEN        NUMBER(10)      PRIMARY KEY,
    ID_CLI            VARCHAR2(10)    NOT NULL,
    RUN_CLI           VARCHAR2(13)    NOT NULL,
    NOMBRE_CLI        VARCHAR2(100)   NOT NULL,
    TIPO_CLI          VARCHAR2(20)    NOT NULL,
    TOTAL_PAGADO      NUMBER(12)      NOT NULL,
    ID_PROF           VARCHAR2(15)    NOT NULL,
    PROMEDIO_RESENA   NUMBER(3,2)     NOT NULL,
    TITULO_PROFESOR   VARCHAR2(20)    NOT NULL,
    FECHA_PROCESO     DATE DEFAULT SYSDATE
);

-- TABLAS A TRABAJAR:

SELECT * FROM CLIENTE;
SELECT * FROM PERSONA_SENSIBLE;
SELECT * FROM CLIENTE_SENSIBLE;
SELECT * FROM CONTRATO;


--CONSULTA PARA CURSOR:

SELECT 
    PER_S.RUN_PER AS RUN_CLIENTE,
    PER_S.PNOMBRE_PER || ' ' || PER_S.PAPELLIDO_PER AS NOMBRE_CLIENTE,
    CLI.ID_CLI AS ID_CLIENTE,
    NVL(CLI_S.TIP_CLI, 'PERSONA NATURAL') AS TIPO_CLIENTE,
    CON.ID_CONT AS ID_CONTRATO,
    CON.PROFESOR_ID_PRO AS ID_PROF
FROM CLIENTE CLI 
JOIN PERSONA_SENSIBLE PER_S ON (CLI.ID_PERSONA = PER_S.ID_PERSONA)
LEFT JOIN CLIENTE_SENSIBLE CLI_S ON (CLI.ID_PERSONA = CLI_S.ID_PERSONA)
JOIN CONTRATO CON ON (CLI.ID_CLI = CON.CLIENTE_ID_CLI); 